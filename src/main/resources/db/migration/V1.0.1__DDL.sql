CREATE TABLE IF NOT EXISTS annee (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS niveau (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS classe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(50) NOT NULL,
    niveau VARCHAR(50),
    effectif_max INTEGER
);

CREATE TABLE IF NOT EXISTS matiere (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(50) NOT NULL,
    coefficient NUMERIC(5, 2)
);

CREATE TABLE IF NOT EXISTS professeur (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(50) NOT NULL,
    prenom VARCHAR(50) NOT NULL,
    email VARCHAR(100),
    matiere_id BIGINT,
    classe_id BIGINT,
    CONSTRAINT fk_professeur_matiere FOREIGN KEY (matiere_id) REFERENCES matiere(id),
    CONSTRAINT fk_professeur_classe FOREIGN KEY (classe_id) REFERENCES classe(id)
);

CREATE TABLE IF NOT EXISTS eleve (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(50) NOT NULL,
    prenom VARCHAR(50) NOT NULL,
    date_naissance DATE,
    matricule VARCHAR(50),
    moyenne_trimestre_courant NUMERIC(5, 2),
    ecart_trimestre_precedent NUMERIC(5, 2),
    est_sigle BOOLEAN,
    trimestre_sigle INTEGER
);

CREATE TABLE IF NOT EXISTS periode (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(50) NOT NULL,
    numero INTEGER NOT NULL,
    cloture BOOLEAN DEFAULT FALSE,
    date_rouverte DATE,
    motif_rouverte VARCHAR(255),
    utilisateur_rouverte VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS type_evaluation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(50) NOT NULL,
    code VARCHAR(50) NOT NULL,
    poid NUMERIC(5, 2) NOT NULL
);

CREATE TABLE IF NOT EXISTS coefficient (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valeur NUMERIC(5, 2) NOT NULL,
    matiere_id BIGINT NOT NULL,
    niveau_id BIGINT NOT NULL,
    CONSTRAINT fk_coefficient_matiere FOREIGN KEY (matiere_id) REFERENCES matiere(id),
    CONSTRAINT fk_coefficient_niveau FOREIGN KEY (niveau_id) REFERENCES niveau(id)
);

CREATE TABLE IF NOT EXISTS inscription (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    annee_id BIGINT NOT NULL,
    classe_id BIGINT NOT NULL,
    eleve_id BIGINT NOT NULL,
    date_debut DATE,
    date_fin DATE,
    CONSTRAINT fk_inscription_annee FOREIGN KEY (annee_id) REFERENCES annee(id),
    CONSTRAINT fk_inscription_classe FOREIGN KEY (classe_id) REFERENCES classe(id),
    CONSTRAINT fk_inscription_eleve FOREIGN KEY (eleve_id) REFERENCES eleve(id)
);

CREATE TABLE IF NOT EXISTS enseignement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matiere_id BIGINT NOT NULL,
    professeur_id BIGINT NOT NULL,
    classe_id BIGINT,
    CONSTRAINT fk_enseignement_matiere FOREIGN KEY (matiere_id) REFERENCES matiere(id),
    CONSTRAINT fk_enseignement_professeur FOREIGN KEY (professeur_id) REFERENCES professeur(id),
    CONSTRAINT fk_enseignement_classe FOREIGN KEY (classe_id) REFERENCES classe(id)
);

CREATE TABLE IF NOT EXISTS note (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valeur NUMERIC(5, 2) NOT NULL,
    date_saisie DATE,
    enseignement_id BIGINT NOT NULL,
    inscription_id BIGINT NOT NULL,
    periode_id BIGINT NOT NULL,
    type_evaluation_id BIGINT NOT NULL,
    CONSTRAINT fk_note_enseignement FOREIGN KEY (enseignement_id) REFERENCES enseignement(id),
    CONSTRAINT fk_note_inscription FOREIGN KEY (inscription_id) REFERENCES inscription(id),
    CONSTRAINT fk_note_periode FOREIGN KEY (periode_id) REFERENCES periode(id),
    CONSTRAINT fk_note_type_eval FOREIGN KEY (type_evaluation_id) REFERENCES type_evaluation(id)
);

CREATE TABLE IF NOT EXISTS salle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(50) NOT NULL,
    capacite INTEGER
);

CREATE TABLE IF NOT EXISTS creneaux (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chreno VARCHAR(50),
    heure_debut TIME(0) WITHOUT TIME ZONE,
    heure_fin TIME(0) WITHOUT TIME ZONE
);

CREATE TABLE IF NOT EXISTS cours (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_cours DATE NOT NULL,
    creneau_id BIGINT NOT NULL,
    enseignement_id BIGINT NOT NULL,
    salle_id BIGINT NOT NULL,
    CONSTRAINT fk_cours_creneau FOREIGN KEY (creneau_id) REFERENCES creneaux(id),
    CONSTRAINT fk_cours_enseignement FOREIGN KEY (enseignement_id) REFERENCES enseignement(id),
    CONSTRAINT fk_cours_salle FOREIGN KEY (salle_id) REFERENCES salle(id)
);

CREATE TABLE IF NOT EXISTS absence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    est_justifiee BOOLEAN NOT NULL,
    inscription_id BIGINT NOT NULL,
    CONSTRAINT fk_absence_inscription FOREIGN KEY (inscription_id) REFERENCES inscription(id)
);

CREATE TABLE IF NOT EXISTS bulettin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    moyenne_generale NUMERIC(5, 2),
    rang INTEGER
);

CREATE TABLE IF NOT EXISTS moyenne_matieres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    moyenne NUMERIC(5, 2) NOT NULL,
    matiere_id BIGINT NOT NULL,
    inscription_id BIGINT NOT NULL,
    bulletin_id BIGINT NOT NULL,
    CONSTRAINT fk_moyenne_matieres_inscription FOREIGN KEY (inscription_id) REFERENCES inscription(id),
    CONSTRAINT fk_moyenne_matieres_bulletin FOREIGN KEY (bulletin_id) REFERENCES bulettin(id)
);

CREATE TABLE IF NOT EXISTS amenagement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle VARCHAR(100) NOT NULL,
    eleve_id BIGINT NOT NULL,
    CONSTRAINT fk_amenagement_eleve FOREIGN KEY (eleve_id) REFERENCES eleve(id)
);

-- =========================================================================
-- INDEX ET CONTRAINTES COMPLÉMENTAIRES
-- =========================================================================

CREATE INDEX IF NOT EXISTS idx_classe_nom ON classe (nom);
CREATE INDEX IF NOT EXISTS idx_matiere_nom ON matiere (nom);
CREATE INDEX IF NOT EXISTS idx_professeur_nom_prenom ON professeur (nom, prenom);
CREATE INDEX IF NOT EXISTS idx_professeur_email ON professeur (email);
CREATE INDEX IF NOT EXISTS idx_eleve_nom_prenom ON eleve (nom, prenom);
CREATE INDEX IF NOT EXISTS idx_eleve_matricule ON eleve (matricule);
CREATE INDEX IF NOT EXISTS idx_note_inscription ON note (inscription_id);
CREATE INDEX IF NOT EXISTS idx_note_periode ON note (periode_id);
CREATE INDEX IF NOT EXISTS idx_note_enseignement ON note (enseignement_id);
